def steps(items):
    """Numbered steps written out (own numbers: Word list numbering restarts are fragile)."""
    for i, t in enumerate(items, 1):
        p = doc.add_paragraph()
        p.paragraph_format.left_indent = Cm(0.0)
        p.paragraph_format.right_indent = Cm(0.9)
        p.paragraph_format.first_line_indent = Cm(-0.9)
        p.paragraph_format.space_after = Pt(4)
        pf = p._p.get_or_add_pPr()
        if pf.find(qn("w:bidi")) is None:
            pf.append(OxmlElement("w:bidi"))
        run(p, f"{str(i).translate(FA)}. ", bold=True, color=TEAL)
        rich(p, t)


