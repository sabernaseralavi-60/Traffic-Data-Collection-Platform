def shade(cell, hexcolor):
    tcpr = cell._tc.get_or_add_tcPr()
    sh = OxmlElement("w:shd")
    sh.set(qn("w:val"), "clear")
    sh.set(qn("w:color"), "auto")
    sh.set(qn("w:fill"), hexcolor)
    tcpr.append(sh)


def borders(tbl, color="94A3B8"):
    tblpr = tbl._tbl.tblPr
    b = OxmlElement("w:tblBorders")
    for edge in ("top", "left", "bottom", "right", "insideH", "insideV"):
        e = OxmlElement(f"w:{edge}")
        e.set(qn("w:val"), "single")
        e.set(qn("w:sz"), "4")
        e.set(qn("w:color"), color)
        b.append(e)
    tblpr.append(b)


def rtl_table(tbl):
    tblpr = tbl._tbl.tblPr
    if tblpr.find(qn("w:bidiVisual")) is None:
        tblpr.append(OxmlElement("w:bidiVisual"))
    tbl.alignment = WD_TABLE_ALIGNMENT.CENTER


def table(header, rows, widths=None, size=9.5):
    t = doc.add_table(rows=1, cols=len(header))
    rtl_table(t)
    borders(t)
    for i, text in enumerate(header):
        c = t.rows[0].cells[i]
        shade(c, "0F766E")
        c.paragraphs[0].paragraph_format.space_after = Pt(2)
        run(c.paragraphs[0], text, bold=True, size=size, color=RGBColor(0xFF, 0xFF, 0xFF))
    for r in rows:
        cells = t.add_row().cells
        for i, text in enumerate(r):
            cells[i].paragraphs[0].paragraph_format.space_after = Pt(2)
            rich(cells[i].paragraphs[0], text, size)
    if widths:
        for row in t.rows:
            for i, w in enumerate(widths):
                row.cells[i].width = Cm(w)
    # repeat the header row on every page
    trpr = t.rows[0]._tr.get_or_add_trPr()
    th = OxmlElement("w:tblHeader")
    th.set(qn("w:val"), "true")
    trpr.append(th)
    doc.add_paragraph().paragraph_format.space_after = Pt(4)
    return t


def callout(kind, text):
    colors = {"نکته": ("ECFDF5", "10B981"), "هشدار": ("FEF2F2", "EF4444"), "توجه": ("FFFBEB", "F59E0B")}
    fill, line = colors[kind]
    t = doc.add_table(rows=1, cols=1)
    rtl_table(t)
    borders(t, line)
    c = t.rows[0].cells[0]
    shade(c, fill)
    p = c.paragraphs[0]
    p.paragraph_format.space_after = Pt(2)
    run(p, f"{kind}: ", bold=True, color=RGBColor.from_string(line))
    rich(p, text)
    doc.add_paragraph().paragraph_format.space_after = Pt(2)


def figure(name, caption, width=15.5):
    path = os.path.join(IMG, name)
    if not os.path.exists(path):
        print("missing image", name, file=sys.stderr)
        return
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.keep_with_next = True
    p.add_run().add_picture(path, width=Cm(width))
    cap = doc.add_paragraph(style="Caption")
    run(cap, caption, size=9.5, color=RGBColor(0x47, 0x55, 0x69))


